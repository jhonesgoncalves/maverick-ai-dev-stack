export async function inspectProject(cwd) {
  const stack = await detectStack(cwd);
  const entries = await readdir(cwd, { withFileTypes: true });
  const directories = entries.filter(entry => entry.isDirectory()).map(entry => entry.name).filter(name => !IGNORED_DIRS.has(name)).sort();
  const files = entries.filter(entry => entry.isFile()).map(entry => entry.name).sort();
  const manifests = [...new Set(stack.ecosystems.flatMap(item => item.manifests))];
  const instructions = (await Promise.all(INSTRUCTION_FILES.map(async name => (await exists(join(cwd, name))) ? name : null))).filter(Boolean);
  const scripts = stack.ecosystems.find(item => item.id === 'node')?.scripts || {};
  return {
    name: stack.name || cwd.split(/[\\/]/).filter(Boolean).pop(), manifests, directories, files: files.slice(0, 40), scripts, commands: stack.commands, instructions,
    language: stack.languages.join(', ') || 'unknown', languages: stack.languages, framework: stack.frameworks.join(', ') || undefined, frameworks: stack.frameworks,
    packageManagers: stack.packageManagers, stack
  };
}

function commandLine(item) { return `- ${item.name}: \`${item.command}\`${item.cwd ? ` (in \`${item.cwd}/\`)` : ''} — ${item.source}`; }

export function renderProjectMap(map) {
  const stack = map.stack || { ecosystems: [], runners: [], subprojects: [] };
  const commands = map.commands.length ? map.commands.map(commandLine).join('\n') : '- No verification commands detected. Declare them in `.maverick/config.json` under `verification.commands`.';
  const ecosystems = stack.ecosystems.map(item => `- ${item.id} (${item.packageManager}): ${item.manifests.join(', ')}`).join('\n') || '- none detected at the root';
  const runners = stack.runners.map(item => `- ${item.id}: \`${item.file}\` (${item.targets.slice(0, 12).join(', ') || 'no targets'})`).join('\n');
  const subprojects = stack.subprojects.map(item => `- \`${item.path}/\`: ${item.ecosystems.map(e => e.id).concat(item.runners.map(r => r.id)).join(', ')}${item.commands.length ? ` — ${item.commands.map(c => c.command).join('; ')}` : ''}`).join('\n');
  return `# Project Map\n\nGenerated by Maverick. Refresh with \`maverick map\`.\n\n## Stack\n- Project: ${map.name}\n- Languages: ${map.language}\n- Frameworks: ${map.framework || 'not detected'}\n- Package managers: ${map.packageManagers?.join(', ') || 'not detected'}\n- Manifests: ${map.manifests.join(', ') || 'none detected'}\n\n## Ecosystems\n${ecosystems}\n${runners ? `\n## Task runners\n${runners}\n` : ''}${subprojects ? `\n## Subprojects\n${subprojects}\n` : ''}\n## Top-level areas\n${map.directories.map(name => `- \`${name}/\``).join('\n') || '- none'}\n\n## Verification commands\n${commands}\n\n## Repository instructions\n${map.instructions.map(name => `- \`${name}\``).join('\n') || '- none detected'}\n\n## Context guidance\nRead the nearest instruction file and only the paths relevant to the task before editing.\n`;
}

