// Commands started while a loop or flow evaluates its gates inherit its timeout and abort signal,
// including commands that in-process Maverick gates (verify, guard...) start several calls deep.
const commandScope = new AsyncLocalStorage();
export function withCommandScope(scope, fn) { return scope?.timeoutMs || scope?.signal ? commandScope.run(scope, fn) : fn(); }

/**
 * Runs a command without a shell, merging stdout and stderr and keeping the last `limit`
 * characters. With a timeout or abort signal the command gets its own process group, so
 * stopping it also stops the processes it started (a test runner's workers, a dev server).
 */
export async function executeCommand(cwd, command, subdir = '', limit = 12000, { timeoutMs, env, signal } = {}) {
  const scope = commandScope.getStore() || {};
  timeoutMs ??= scope.timeoutMs; signal ??= scope.signal;
  let bin, args;
  try { [bin, ...args] = splitCommand(command); } catch (error) { return { command, cwd: subdir, ok: false, code: null, output: error.message }; }
  const label = subdir ? `${command} (in ${subdir}/)` : command;
  if (signal?.aborted) return { command: label, ok: false, code: null, output: 'aborted before starting', aborted: true };
  return new Promise(resolve => {
    const detached = process.platform !== 'win32' && Boolean(timeoutMs || signal);
    // The sealed-test key never reaches a command a check runs: those run code an agent wrote.
    const child = spawn(bin, args, { cwd: subdir ? join(cwd, subdir) : cwd, shell: false, stdio: ['ignore', 'pipe', 'pipe'], detached, env: { ...process.env, MAVERICK_SEAL_KEY: undefined, ...env } });
    let output = '', timedOut = false, aborted = false, settled = false;
    const kill = sig => { try { if (detached) process.kill(-child.pid, sig); else child.kill(sig); } catch { /* already gone */ } };
    const stop = () => { if (child.exitCode !== null) return; kill('SIGTERM'); setTimeout(() => { if (child.exitCode === null) kill('SIGKILL'); }, 3000).unref(); };
    const timer = timeoutMs > 0 ? setTimeout(() => { timedOut = true; stop(); }, timeoutMs) : null;
    const onAbort = () => { aborted = true; stop(); };
    signal?.addEventListener('abort', onAbort, { once: true });
    const finish = result => {
      if (settled) return; settled = true;
      if (timer) clearTimeout(timer);
      signal?.removeEventListener('abort', onAbort);
      const note = timedOut ? `\n[stopped: timed out after ${Math.max(1, Math.round(timeoutMs / 1000))}s]` : aborted ? '\n[stopped: aborted]' : '';
      resolve({ command: label, ...result, ok: result.ok && !timedOut && !aborted, output: `${result.output}${note}`, ...(timedOut && { timedOut }), ...(aborted && { aborted }) });
    };
    const collect = chunk => { output += chunk; if (output.length > limit * 2) output = output.slice(-limit); };
    child.stdout.on('data', collect); child.stderr.on('data', collect);
    child.on('error', error => finish({ ok: false, code: null, output: error.message }));
    child.on('close', code => finish({ ok: code === 0, code, output: output.slice(-limit) }));
  });
}

const DIFF_LIMIT = 20 * 1024 * 1024, UNTRACKED_TEXT_LIMIT = 256 * 1024;

// A file git does not track yet, rendered as a new-file diff so every diff gate sees it.
async function untrackedDiff(cwd, file) {
  const header = `diff --git a/${file} b/${file}\nnew file mode 100644\n--- /dev/null\n+++ b/${file}\n`;
  const buffer = await readFile(join(cwd, file)).catch(() => null);
  if (!buffer || buffer.length > UNTRACKED_TEXT_LIMIT || buffer.includes(0)) return header;
  const lines = buffer.toString('utf8').replace(/\n$/, '').split('\n');
  return `${header}@@ -0,0 +1,${lines.length} @@\n${lines.map(line => `+${line}`).join('\n')}\n`;
}

// --relative keeps the diff to the project directory, with paths relative to it: a project
// nested inside another repository (a monorepo package, an example) never sees its parent's changes.
// Untracked files count as changes too, so files a task creates are checked before `git add`;
// .maverick/ is left out, tracked or not, because it holds the task's own artifacts and reports.
export async function gitDiff(cwd, against = 'HEAD') {
  const [result, others] = await Promise.all([
    // Fixed flags, so user settings (diff.noprefix, color.ui=always, external diff tools) cannot hide changes from the gates.
    executeCommand(cwd, `git -c core.quotePath=false diff ${against} --relative --no-color --no-ext-diff --src-prefix=a/ --dst-prefix=b/ -- . :(exclude).maverick`, '', DIFF_LIMIT),
    executeCommand(cwd, 'git ls-files --others --exclude-standard -z -- . :(exclude).maverick', '', DIFF_LIMIT)
  ]);
  const tracked = result.ok ? result.output : '';
  // Without a baseline every file is untracked, and listing them all says nothing about the task.
  if (!others.ok || await lacksGitBaseline(cwd)) return tracked;
  const files = others.output.split('\0').filter(Boolean);
  return tracked + (await Promise.all(files.map(file => untrackedDiff(cwd, file)))).join('');
}

export async function writeEvidence(dir, task, results) {
  await mkdir(dir, { recursive: true });
  const body = `# Verification Evidence — ${task}\n\nGenerated: ${new Date().toISOString()}\n\n${results.map(result => `## ${result.ok ? 'PASS' : 'FAIL'} — ${result.command}\nExit code: ${result.code ?? 'not started'}\n\n\`\`\`text\n${(result.output || '(no output)').slice(-12000)}\n\`\`\``).join('\n\n')}\n`;
  const path = join(dir, 'EVIDENCE.md'); await writeFile(path, body); return path;
}

/** True inside a git repository that tracks no file of this directory: a diff cannot separate the task's changes from the project. */
export async function lacksGitBaseline(cwd) {
  const result = await executeCommand(cwd, 'git ls-files -- .', '', 4096);
  return result.ok && result.output.trim() === '';
}

export async function changedFiles(cwd, against = 'HEAD') { return changedFilesFromDiff(await gitDiff(cwd, against)); }

export async function findReferences(cwd, target, maxResults = 40) {
  const needle = target.split('/').pop().replace(/\.[^.]+$/, '');
  const results = [];
  async function visit(directory) {
    if (results.length >= maxResults) return;
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (results.length >= maxResults || IGNORED_DIRS.has(entry.name)) continue;
      const path = join(directory, entry.name);
      if (entry.isDirectory()) await visit(path);
      else if (entry.isFile()) {
        try {
          const text = await readFile(path, 'utf8');
          if (text.includes(needle)) results.push(relative(cwd, path));
        } catch { /* Ignore binary and unreadable files. */ }
      }
    }
  }
  await visit(cwd);
  return results;
}
