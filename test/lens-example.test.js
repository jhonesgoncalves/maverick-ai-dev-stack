import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
import { join } from 'node:path';
import { createLensExample } from '../scripts/lens-example-project.mjs';
import { createLoopHub } from '../src/lens/loops.js';
import { decisionDashboard, holdoutDashboard } from '../src/lens/decide.js';
import { readLedger, verifyChain } from '../src/loop/ledger.js';
import { readLock, checkDrift } from '../src/capabilities/engine.js';
import { listProposals } from '../src/memory/proposals.js';
import { listContracts } from '../src/memory/contracts.js';
import { sealPaths } from '../src/sealed/model.js';
import { readVaultJson, vaultKey } from '../src/sealed/vault.js';
import { aad } from '../src/sealed/model.js';

test('Lens example supplies complete proof, calibration and memory fixtures without real providers or user-home writes', async t => {
  const previousHome = process.env.MAVERICK_HOME, example = await createLensExample();
  t.after(example.cleanup);
  assert.ok(example.home.startsWith(example.root.replace(/northstar-orders$/, '')));
  assert.notEqual(example.home, previousHome);
  const dashboard = await decisionDashboard(example.root);
  assert.equal(dashboard.scorecard.warnings.length, 0);
  assert.ok(dashboard.scorecard.groups.some(g => g.provider === 'codex' && g.iterations >= 30 && g.safetyScore > 0.5));
  assert.ok(dashboard.scorecard.groups.some(g => g.integrity > 0 && g.OI.max > 0));
  assert.ok(dashboard.scorecard.groups.some(g => g.costUnknown > 0));
  assert.ok(dashboard.scorecard.groups.some(g => g.type === 'judge'));
  assert.ok(dashboard.scorecard.groups.some(g => g.passK[2].samples > 0));
  assert.ok(dashboard.rubrics.some(r => r.labels >= 30 && r.eligible));
  assert.ok(dashboard.rubrics.some(r => r.labels < 30 && !r.eligible));
  const holdouts = await holdoutDashboard(example.root);
  assert.equal(holdouts.tasks.length, 6);
  assert.equal(holdouts.warnings.length, 0);
  assert.ok(holdouts.tasks.every(t => t.ledgerValid));
  assert.ok(holdouts.tasks.some(t => t.amended && t.suspended));
  assert.ok(holdouts.tasks.some(t => t.state === 'committed'));
  assert.ok(holdouts.tasks.some(t => t.review.verdict === 'fail' && !t.approval));
  assert.ok(holdouts.cohorts.some(c => c.defects.rate > 0));
  assert.ok(!JSON.stringify(holdouts).includes('FICTIONAL_HOLDOUT_CONTENT'));
  const suite = holdouts.tasks.find(t => t.OI > 0), key = await vaultKey({}, example.root);
  const encrypted = await readFile(sealPaths(example.root, suite.task, suite.sealId).suite);
  assert.ok(!encrypted.toString().includes('FICTIONAL_HOLDOUT_CONTENT'));
  const opened = await readVaultJson(sealPaths(example.root, suite.task, suite.sealId).suite, key, aad(suite.sealId, 'suite'));
  assert.match(opened.files[0].content, /FICTIONAL_HOLDOUT_CONTENT/);
  const hub = createLoopHub({ cwd: example.root, broadcast: () => {} }); t.after(() => hub.close());
  const loops = await hub.list();
  for (const status of ['done', 'aborted', 'disputed', 'stalled-escalated', 'budget-exceeded', 'holdout-gap']) assert.ok(loops.loops.some(l => l.status === status), `missing ${status}`);
  for (const loop of example.evidence.loops) assert.equal((await hub.ledger(loop.task, loop.id)).ok, true, `invalid checkpoint/ledger for ${loop.task}/${loop.id}`);
  const gap = await hub.detail('repair-cursor-boundary', '20261012-110000-f004');
  assert.ok(gap.decisions.some(d => d.rubric === 'integrity' && d.advisory));
  const yieldLoop = await hub.detail('add-orders-pagination', '20261012-090000-f002');
  assert.equal(yieldLoop.state.iterations.at(-1).yield.low, true);
  const calibration = await readLedger(join(example.root, '.maverick/decisions/integrity.jsonl'));
  assert.equal(verifyChain(calibration, 'integrity').ok, true);
  const rules = await listProposals(example.root);
  assert.ok(rules.some(r => r.status === 'accepted')); assert.ok(rules.some(r => r.status === 'rejected'));
  assert.equal((await listContracts(example.root)).length, 1);
  const drift = await checkDrift(example.root, await readLock(example.root));
  assert.ok(drift.some(d => d.ref === 'skill/safe-review' && !d.issues.length));
  assert.ok(drift.some(d => d.ref === 'agent/read-only-reviewer' && d.issues.length));
  assert.ok(example.evidence.routes.length > 0);
  const config = JSON.parse(await readFile(join(example.root, '.maverick/config.json'), 'utf8'));
  assert.equal(config.runtime.routes[0].provider, 'claude-code', 'a recommendation must not apply itself');
  for (const bin of Object.values(config.runtime.bins)) { assert.ok(bin.startsWith(example.home)); await access(bin); }
  await example.cleanup();
  assert.equal(process.env.MAVERICK_HOME, previousHome);
  await assert.rejects(access(example.root), /ENOENT/);
});
